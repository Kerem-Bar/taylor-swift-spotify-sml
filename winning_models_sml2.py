# 2. Extract standard deviations ('std')
plot_summary = df_test_final.groupby(['album_families', 'release_year']).agg(
    Actual_Data=('popularity', 'std'),
    Random_Forest=('RF_Predicted', 'std'),
    Gradient_Boosting=('GB_Predicted', 'std')
).reset_index()

plot_summary['Album_Era'] = plot_summary['album_families'] + " (" + plot_summary['release_year'].astype(str) + ")"

# 3. Melt for Seaborn
df_melted_bars = plot_summary.melt(
    id_vars=['Album_Era'], value_vars=['Actual_Data', 'Random_Forest', 'Gradient_Boosting'],
    var_name='Model_Type', value_name='Standard_Deviation'
)
df_melted_bars['Model_Type'] = df_melted_bars['Model_Type'].map({
    'Actual_Data': 'Actual Song Variance',
    'Random_Forest': 'Random Forest (Depth 4)',
    'Gradient_Boosting': 'Gradient Boosting (Depth 4)'
})

