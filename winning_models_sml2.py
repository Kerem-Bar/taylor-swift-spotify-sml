# 2. Random Forest Model Tuning (With energy and without outliers)
x_forest = df_forest.drop(columns=['popularity', 'album_families'], axis=1)
y_forest = df_forest['popularity']

# Splitting df_forest into train-test by album families
gss_forest = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
train_idx_f, test_idx_f = next(gss_forest.split(x_forest, y_forest, groups=df_forest['album_families']))

# go to x_forest and y_forest and bring only the cells from indexes
x_train_f = x_forest.iloc[train_idx_f].copy()
y_train_f = y_forest.iloc[train_idx_f].copy()
x_test_f = x_forest.iloc[test_idx_f].copy()
y_test_f = y_forest.iloc[test_idx_f].copy()

# Feature Scaling (Normalization)
scaler_f = StandardScaler()
x_train_scaled_f = scaler_f.fit_transform(x_train_f)
x_test_scaled_f = scaler_f.transform(x_test_f)

# Creating lists to store metrics for each depth
rmse_train_forest = []
rmse_test_forest = []
r2_train_forest = []
r2_test_forest = []

# Running the loop for max_depth from 1 to 10
for i in range(1, 11):
    forest_model=RandomForestRegressor(n_estimators=100, max_depth=i, random_state=42)
    forest_model.fit(x_train_scaled_f, y_train_f)

    # Predicting popularity scores
    y_predict_train_forest = forest_model.predict(x_train_scaled_f)
    y_predict_test_forest = forest_model.predict(x_test_scaled_f)

    # Calculating evaluation metrics
    rmse_forest_train = root_mean_squared_error(y_train_f, y_predict_train_forest)
    rmse_forest_test = root_mean_squared_error(y_test_f, y_predict_test_forest)
    r2_forest_train = r2_score(y_train_f, y_predict_train_forest)
    r2_forest_test = r2_score(y_test_f, y_predict_test_forest)

    # Printing the final cleaned results for each depth
    print(f"RF Clean Depth {i} -> Train RMSE: {rmse_forest_train:.4f} | Test RMSE: {rmse_forest_test:.4f} | Train R2: {r2_forest_train:.4f} | Test R2: {r2_forest_test:.4f}")

    # Appending metrics to lists
    rmse_train_forest.append(rmse_forest_train)
    rmse_test_forest.append(rmse_forest_test)
    r2_train_forest.append(r2_forest_train)
    r2_test_forest.append(r2_forest_test)

